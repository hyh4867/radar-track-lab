from radar_track_lab.metrics import mean_ci  # noqa: E402

D = ROOT / "results/data/stage2"
EVAL = "EHAM_1106_eval"
SITE_KO = {"EHAM": "스히폴", "EGLL": "런던 히스로", "KATL": "애틀랜타", "LSZH": "취리히", "YSSY": "시드니", "ENGM": "오슬로"}


def J(name):
    p = D / name
    return json.loads(p.read_text()) if p.exists() else None


def pm(s, nd=1):
    return f"{s['mean']:,.{nd}f} ± {s['ci95']:,.{nd}f}"


def ci(s, nd=1):
    return f"{s['mean']:+,.{nd}f} [{s['lo']:+,.{nd}f}, {s['hi']:+,.{nd}f}]"


def q5_rows():
    """(lambda, m, n) -> stats for the Q5 evaluation runs, if present."""
    out = {}
    for p in sorted((D / "runs").glob(f"{EVAL}__ekf__lam*_m*n*.json")):
        tag = p.stem.split("__")[2]
        lam = float(tag.split("_")[0][3:])
        m, n = (int(x) for x in tag.split("_")[1][1:].split("n"))
        runs = json.loads(p.read_text())["runs"]
        st = {}
        for k in ("false_tracks_per_scan", "missed_per_scan", "init_delay_mean_s", "id_switches", "rmse_m", "gospa_mean_m"):
            mu, h = mean_ci(np.array([r["summary"][k] for r in runs], dtype=float))
            st[k] = {"mean": mu, "ci95": h}
        st["n_runs"] = len(runs)
        out[(lam, m, n)] = st
    return out


def scen_label(e):
    s = e["spec"]
    return f"{s['site']} {s['day']} {s['start_utc'][11:16]}"


def ordered(S):
    sc = S["scenarios"]
    return sorted((k for k in sc if sc[k]["spec"]["kind"] != "tune" and "imm_vs_ekf" in sc[k]),
                  key=lambda k: (k != EVAL, sc[k]["spec"]["day"], sc[k]["spec"]["site"] != "EHAM", sc[k]["spec"]["site"], k))


