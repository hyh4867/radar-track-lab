def _fill(t: str, tag: str, body: str) -> str:
    a, b = f"<!-- {tag}:begin -->", f"<!-- {tag}:end -->"
    return t[:t.index(a) + len(a)] + "\n" + body + "\n" + t[t.index(b):] if a in t and b in t else t


