"""Render results/RESULTS.md from the JSON outputs (numbers are never typed by hand)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "results/data"


def f(v, nd=1):
    return "n/a" if v != v else f"{v:,.{nd}f}"


def mc(s, key, nd=1):
    return f"{f(s[key]['mean'], nd)} ± {f(s[key]['ci95'], nd)}"


def clutter_density(lam, r_km, r_min=1.0, r_max=100.0):
    """False detections per km^2 per scan at range r (uniform in range and azimuth)."""
    import math
    return lam / (2 * math.pi * r_km * (r_max - r_min))


def main() -> None:
    cmp_ = json.loads((D / "compare.json").read_text())
    nees = json.loads((D / "nees_synthetic.json").read_text())
    tr = json.loads((D / "truth_report.json").read_text())
    sw = json.loads((D / "sweep_summary.json").read_text())
    tq = json.loads((D / "tune_q.json").read_text())
    ids = json.loads((D / "id_switch_diagnosis.json").read_text())
    L = []
    r = cmp_["condition"]
    L += ["# Results", "",
          "Generated by `scripts/write_results_md.py` from `results/data/*.json`.", "",
          "## 1. Tracker vs baseline (default condition)", "",
          f"Radar: Pd = {r['pd']}, clutter λ = {r['clutter_lambda']}/scan, σr = {r['sigma_r_m']:.0f} m, "
          f"σθ = {r['sigma_az_deg']}°, T = {r['rotation_period_s']} s. "
          f"Truth: {cmp_['scenario']['targets']} aircraft, {cmp_['scenario']['truth_per_scan_mean']:.1f} per scan "
          f"on average (max {cmp_['scenario']['truth_per_scan_max']}), 30 min. "
          "20 Monte Carlo runs, mean ± 95% t-interval of the mean. The first 60 s are excluded.", "",
          "| Metric | EKF + GNN | NN baseline |", "|---|---:|---:|"]
    e, n = cmp_["methods"]["ekf"]["summary"], cmp_["methods"]["nn"]["summary"]
    rows = [
        ("Mean GOSPA [m]", "gospa_mean_m", 0),
        ("  localisation part [m]", "gospa_loc_m", 0),
        ("  missed-target part [m]", "gospa_missed_m", 0),
        ("  false-track part [m]", "gospa_false_m", 0),
        ("Missed targets per scan", "missed_per_scan", 2),
        ("False tracks per scan", "false_tracks_per_scan", 2),
        ("Position RMSE at evaluation time [m]", "rmse_m", 1),
        ("Position RMSE at update time [m]", "rmse_at_update_m", 1),
        ("ID switches (30 min)", "id_switches", 1),
        ("Track breaks (30 min)", "fragmentations", 1),
        ("Initiation delay, mean [s]", "init_delay_mean_s", 1),
        ("Initiation delay, median [s]", "init_delay_median_s", 1),
    ]
    for label, key, nd in rows:
        L.append(f"| {label} | {mc(e, key, nd)} | {mc(n, key, nd)} |")
    L += ["", "GOSPA parts are root-mean values of the additive terms: "
          "mean(GOSPA²) = loc² + missed² + false².", ""]

    L += ["## 2. Filter consistency (NEES)", "",
          "| Case | samples | ANEES (4-D) | 95% interval for that many samples | steps inside per-step interval |",
          "|---|---:|---:|---|---:|"]
    for k, v in nees.items():
        L.append(f"| {v['label'].replace('lambda', 'λ')} | {v['samples']:,} | {v['anees4_overall']:.2f} | "
                 f"[{v['overall_bounds4'][0]:.2f}, {v['overall_bounds4'][1]:.2f}] | "
                 f"{v['frac_steps_inside4']*100:.1f}% |")
    a = nees["A_pd1_clutter0"]
    L += ["", f"Case A, targets beyond 5 km: ANEES {a['anees4_range_ge_5km']:.3f} "
          f"(interval [{a['bounds4_range_ge_5km'][0]:.3f}, {a['bounds4_range_ge_5km'][1]:.3f}]); "
          f"within 5 km: {a['anees4_range_lt_5km']:.1f} over {a['samples_range_lt_5km']} samples. "
          f"Largest single NEES {a['max_nees4']:.0f} at {a['range_of_max_nees4_m']/1000:.1f} km.", ""]
    nr = cmp_["nees_real_adsb"]
    L += [f"Real ADS-B truth (default condition, confirmed tracks, {nr['samples_confirmed']:,} samples): "
          f"ANEES {nr['anees4_confirmed']:.2f}, median NEES {nr['median_nees4_confirmed']:.2f}, "
          f"{nr['frac_nees4_le_chi2_95']*100:.1f}% of samples below the χ²(4) 95% point.", ""]

    L += ["## 3. Noise sweep (20 runs each; RMSE and GOSPA ± 95% t-interval)", "",
          "| Pd | λ | σθ | RMSE EKF [m] | RMSE NN [m] | ID sw. EKF | ID sw. NN | GOSPA EKF [m] | GOSPA NN [m] |",
          "|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    by = {(c["pd"], c["clutter_lambda"], c["sigma_az_deg"], c["method"]): c["summary"] for c in sw["conditions"]}
    for pd, lam, saz in sorted({k[:3] for k in by}):
        ee, nn = by[(pd, lam, saz, "ekf")], by[(pd, lam, saz, "nn")]
        L.append(f"| {pd} | {lam} | {saz:.2f}° | {mc(ee, 'rmse_m', 1)} | {mc(nn, 'rmse_m', 1)} | "
                 f"{f(ee['id_switches']['mean'])} | {f(nn['id_switches']['mean'])} | "
                 f"{mc(ee, 'gospa_mean_m', 0)} | {mc(nn, 'gospa_mean_m', 0)} |")
    L += ["", "Per-run values: `results/data/sweep_runs.csv`.", ""]

    hv_path = D / "sweep_heavy_clutter.json"
    L += ["### 3a. Clutter density", "",
          "Clutter is uniform in range (1-100 km) and azimuth, so the density per area falls as 1/r. "
          "Coverage area 31,413 km².", "",
          "| λ per scan | mean density [/km²/scan] | at 10 km | at 50 km | at 90 km |", "|---:|---:|---:|---:|---:|"]
    for lam in (5, 20, 200, 1000):
        L.append(f"| {lam} | {lam / 31412.7:.1e} | {clutter_density(lam, 10):.1e} | {clutter_density(lam, 50):.1e} | "
                 f"{clutter_density(lam, 90):.1e} |")
    L.append("")
    if hv_path.exists():
        hv = json.loads(hv_path.read_text())["conditions"]
        hb = {(c["clutter_lambda"], c["method"]): c["summary"] for c in hv}
        L += ["### 3b. Dense clutter (Pd 0.9, σθ 0.15°, 20 runs each)", "",
              "| λ | method | RMSE [m] | ID switches | false tracks / scan | missed / scan | tracks / scan | GOSPA [m] |",
              "|---:|---|---:|---:|---:|---:|---:|---:|"]
        rows_l = [(lam, m, by[(0.9, lam, 0.15, m)]) for lam in (0, 5, 20) for m in ("ekf", "nn")]
        rows_l += [(lam, m, hb[(lam, m)]) for lam in sorted({c["clutter_lambda"] for c in hv}) for m in ("ekf", "nn")]
        for lam, m, sm in rows_l:
            L.append(f"| {lam} | {'EKF + GNN' if m == 'ekf' else 'NN baseline'} | {mc(sm, 'rmse_m', 1)} | "
                     f"{mc(sm, 'id_switches', 1)} | {mc(sm, 'false_tracks_per_scan', 2)} | {mc(sm, 'missed_per_scan', 2)} | "
                     f"{f(sm['tracks_per_scan']['mean'])} | {mc(sm, 'gospa_mean_m', 0)} |")
        L.append("")

    fs = tr["filter_stats"]
    L += ["## 4. Ground truth", "",
          f"Evaluation window {tr['window_utc'][0]} + {tr['window_utc'][1]:.0f} s (with 120 s margins for filtering).", "",
          "| Step | points |", "|---|---:|",
          f"| ADS-B/MLAT points in the 125 km box | {fs['total_points']:,} |",
          f"| dropped: source not `adsb_icao` (MLAT etc.) | {fs['dropped_source']:,} |",
          f"| dropped: stale position flag | {fs['dropped_stale']:,} |",
          f"| dropped: on ground | {fs['dropped_ground']:,} |",
          f"| dropped: NACp unknown | {fs['dropped_unknown_nacp']:,} |",
          f"| dropped: NACp < 8 | {fs['dropped_low_nacp']:,} |",
          f"| kept (in {tr['segments']} segments, {tr['aircraft']} aircraft) | {fs['kept_points']:,} |", "",
          f"NACp histogram of airborne `adsb_icao` points: {fs['nacp_hist']}", "",
          "Interpolation error (leave-one-out, cubic Hermite with ADS-B velocity vs linear):", "",
          "| gap between neighbours [s] | n | Hermite RMS [m] | Hermite p95 [m] | linear RMS [m] |", "|---|---:|---:|---:|---:|"]
    for b in tr["loo_by_gap"]:
        h, li = b["hermite"], b["linear"]
        if h["n"]:
            L.append(f"| {b['gap_s'][0]}-{b['gap_s'][1]} | {h['n']:,} | {h['rms_m']:.1f} | {h['p95_m']:.1f} | {li['rms_m']:.1f} |")
    la = tr["loo_all"]
    L += ["", f"All samples: Hermite median {la['hermite']['median_m']:.1f} m, RMS {la['hermite']['rms_m']:.1f} m, "
          f"p95 {la['hermite']['p95_m']:.1f} m. Gaps actually bracketing radar illumination times: median "
          f"{tr['used_bracket_gap_s']['median']:.1f} s, p95 {tr['used_bracket_gap_s']['p95']:.1f} s. "
          f"Estimated RMS interpolation error at those gaps: "
          f"{tr['estimated_interp_rms_at_used_gaps_m']['mean_of_bin_rms']:.1f} m.", ""]

    L += ["## 5. Process-noise tuning (tuning window only)", "",
          f"Window {tq['window'][0]} + {tq['window'][1]} s. Criterion: {tq['criterion']}. Selected q = {tq['selected_q']} m²/s³.", "",
          "| q [m²/s³] | mean GOSPA [m] | RMSE [m] | ID switches |", "|---:|---:|---:|---:|"]
    for g in tq["grid"]:
        L.append(f"| {g['q']} | {g['gospa_mean_m']:.0f} | {g['rmse_m']:.1f} | {g['id_switches']:.1f} |")
    m = ids["mean_per_run"]
    L += ["", "## 6. EKF error breakdown (default condition, 20 runs)", "", "ID switches per run, by cause:", "",
          f"- after an ADS-B truth gap (> 20 s, target absent from truth and simulation): {m['after_truth_gap']:.1f}",
          f"- another truth target within 3 km (crossing / merging traffic in 2-D): {m['near_other']:.1f}",
          f"- other (track lost while the target was continuously present): {m['other']:.1f}", "",
          "False tracks per scan, by cause:", "",
          f"- coasting after its target left the truth (landed, left coverage, ADS-B gap): "
          f"{ids['false_tracks_per_scan']['after_truth_end']:.2f}",
          f"- never matched to any target (clutter-born or duplicate): {ids['false_tracks_per_scan']['never_matched']:.2f}",
          f"- other (target still present but farther than c or matched to another track): "
          f"{ids['false_tracks_per_scan']['other']:.2f}", "",
          "Missed targets per scan, by cause:", "",
          f"- not yet tracked since entering (M-of-N confirmation delay): {ids['missed_per_scan']['before_first_track']:.2f}",
          f"- tracked before, lost or farther than c: {ids['missed_per_scan']['other']:.2f}", ""]
    (ROOT / "results/RESULTS.md").write_text("\n".join(L))
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
